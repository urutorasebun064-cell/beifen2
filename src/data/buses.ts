import type { LineJson } from "@/lib/rail/types";

type Stop = [string, number, number];

function bus(id: string, name: string, color: string, headway: number, stops: Stop[]): LineJson {
  return {
    id,
    name,
    color,
    kind: "bus",
    headway,
    speed: 18,
    loop: false,
    path: stops.map((s) => [s[1], s[2]]),
    stops: stops.map((s, i, a) => ({
      n: s[0],
      lng: s[1],
      lat: s[2],
      pf: "東京都",
      pv: a[i - 1]?.[0] ?? null,
      nx: a[i + 1]?.[0] ?? null,
    })),
  };
}

