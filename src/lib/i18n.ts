export { toJa, toZh };

export function displayName(text: string, lang: Lang) {
  if (!text) return text;
  if (lang === "zh") return toZh(text);
  if (lang === "en") {
    const fn = (globalThis as unknown as { __jbToEn?: (s: string) => string }).__jbToEn;
    return fn ? fn(text) : text;
  }
  return text;
}

